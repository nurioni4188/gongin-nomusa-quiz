        "- 노동경제학은 원문 수식·그래프·수치 일치 검산",
        "- 최종 서면승인 시 ID와 textSHA256 일치, 검토자 자격·독립성·검토일 확인",
        "- 50점 8~10장, 25점 4장, 15점 3장, 10점 이하 2장은 직접 필기 실측 없이 PASS 금지",
