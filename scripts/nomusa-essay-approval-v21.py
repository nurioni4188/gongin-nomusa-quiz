def test():
    assert kind("노동경제학")=="ECONOMIC_MODEL"
    assert kind("인사노무관리론")=="ACADEMIC_THEORY"
    assert kind("노동법Ⅱ")=="HISTORICAL_LAW_AND_PRECEDENT"
    r={"id":"test","year":2022,"subject":"노동법1","points":25,
       "sourceText":"시험원문 임시 예시 문장", "detailed":"제26조 짧은 초안",
       "compressed":"요약","parts":[{"points":25}]}
    c=classify(r,set())
    assert c["reviewTier"]=="P0_2022_PILOT"
    assert c["approvalStatus"]=="HOLD_INDEPENDENT_CONTENT_APPROVAL"
    assert c["proxyDeficitChars"]>0 and c["independentReviewer"] is None
    assert "NO_CASE_NUMBER_TOKEN_IN_DRAFT" in c["issueCodes"]
    assert sha256("a") == hashlib.sha256(b"a").hexdigest()
    print("PASS_V21_PREAPPROVAL_SELF_TEST")

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("root",nargs="?",default=".")
    parser.add_argument("--self-test",action="store_true")
    a=parser.parse_args()
    try:
        if a.self_test:
            test()
        else:
            x=build(Path(a.root))
            print(json.dumps({k:x[k] for k in ("status","count","pilot2022",
              "pilot2022Parts","v20Revised","pointEvidence","proxyFlagged",
              "proxyFlagged50","proxyFlagged25","independentExpertApproved",
              "actualScriptSeconds")},ensure_ascii=False))
    except Exception as exc:
        print(json.dumps({"status":"HOLD_V21_PREAPPROVAL","error":str(exc)},
                         ensure_ascii=False), file=sys.stderr)
        return 2
    return 0

if __name__ == "__main__":
    sys.exit(main())
